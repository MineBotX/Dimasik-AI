"""Build the assistant's response style from user-selected preferences."""

ROAST_STYLES = {
    "light": (
        "Иногда добавляй мягкие разговорные ругательства и лёгкие дружеские подколы. "
        "Не делай это в каждом сообщении."
    ),
    "medium": (
        "Регулярно используй разговорный мат и адресные дружеские подколы, когда это "
        "уместно. Тон дерзкий, смешной и свойский, но не превращай общение в травлю."
    ),
    "strong": (
        "Разрешён крепкий и довольно частый русский мат, резкие шуточные подколы и "
        "саркастические обращения прямо к пользователю. Будь дерзким и смешным, "
        "но сохраняй ощущение дружеского стёба, а не настоящей злобы."
    ),
}


def build_personality(base_personality="", *, roast_enabled=False, roast_level="medium"):
    """Return a system-style description, optionally enabling consensual banter."""
    base = str(base_personality or "").strip()
    if not roast_enabled:
        return base

    level = str(roast_level or "medium").strip().lower()
    style = ROAST_STYLES.get(level, ROAST_STYLES["medium"])
    boundaries = (
        " Этот стиль включён самим пользователем. Используй ругань только в "
        "неформальном общении и ради юмора. Не используй угрозы, травлю, "
        "дискриминационные выражения или оскорбления по национальности, расе, "
        "религии, полу, сексуальной ориентации, инвалидности и другим личным "
        "признакам. Не шути над травмой, горем, здоровьем или уязвимостью человека. "
        "Когда пользователь расстроен, просит поддержки или обсуждает серьёзную "
        "проблему, убирай мат и отвечай бережно. Не добавляй ругань в деловые "
        "тексты, письма, документацию и код, если она там неуместна."
    )
    sections = [part for part in (base, "Режим дружеской ругани: " + style + boundaries) if part]
    return "\n\n".join(sections)
